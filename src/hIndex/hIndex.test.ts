import { hIndex } from './hIndex';

describe('hIndex', () => {
  it('пример 1: [3,0,6,1,5] -> 3', () => {
    expect(hIndex([3, 0, 6, 1, 5])).toBe(3);
  });

  it('пример 2: [1,3,1] -> 1', () => {
    expect(hIndex([1, 3, 1])).toBe(1);
  });

  it('все нули -> 0', () => {
    expect(hIndex([0, 0, 0])).toBe(0);
  });

  it('одна статья с 0 цитат -> 0', () => {
    expect(hIndex([0])).toBe(0);
  });

  it('одна статья с 1 цитатой -> 1', () => {
    expect(hIndex([1])).toBe(1);
  });

  it('одна статья с 100 цитатами -> 1', () => {
    expect(hIndex([100])).toBe(1);
  });

  it('все статьи с одинаковыми цитатами -> n', () => {
    expect(hIndex([5, 5, 5, 5, 5])).toBe(5);
  });

  it('возрастающий порядок -> корректный h-index', () => {
    expect(hIndex([0, 1, 3, 5, 6])).toBe(3);
  });

  it('убывающий порядок -> тот же результат', () => {
    expect(hIndex([6, 5, 3, 1, 0])).toBe(3);
  });

  it('большие значения цитат -> h ограничен числом статей', () => {
    expect(hIndex([1000, 1000, 1000])).toBe(3);
  });
});
